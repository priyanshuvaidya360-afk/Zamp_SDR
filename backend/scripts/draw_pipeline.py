"""Draw the pipeline into agents/PIPELINE.md, straight from the LangGraph graph the app runs.

  cd backend && .venv/bin/python -m scripts.draw_pipeline          # rewrite the file
  cd backend && .venv/bin/python -m scripts.draw_pipeline --check  # exit 1 if it is out of date

The first diagram is generated from the compiled graph (app/pipeline/graph.py), so it cannot
drift from the code: add or reorder a stage and run this again. GitHub and most editors render
the Mermaid blocks.
"""

import sys

from app.config import REPO_DIR
from app.pipeline.graph import build_graph
from app.pipeline.stages import STAGE_INFO, STAGES

TARGET = REPO_DIR / "agents" / "PIPELINE.md"

HEADER = """# The pipeline

> Generated by `backend/scripts/draw_pipeline.py` from the LangGraph graph in
> `backend/app/pipeline/graph.py`. Do not edit by hand: change the code, then run the script.

Every prospect in a CSV runs through this graph on its own. Code decides the order; a model
only makes judgements inside a stage. Each stage that uses a model has its words in an
[agent file](README.md).

## One prospect, stage by stage

Solid arrows: the next stage. Dotted arrows to the end: any stage can stop the run early
with a status (blocked, suppressed, held, needs input, low signal, failed), and the stages
after it are marked "not run".
"""

AROUND = """
## Before and after the graph

The graph is one prospect. Around it, the app also does these things (plain code, no graph):

```mermaid
flowchart LR
  CSV["CSV upload"] --> ING["Ingest<br/>clean, check, dedupe rows"]
  ING --> RUNS["One graph run per valid row<br/>5 at a time"]
  RUNS --> SIM["Batch check<br/>draft similarity, hook-source cap"]
  SIM -.->|over the cap: score again| RUNS
  SIM --> Q["Review queue<br/>approve, edit, reject"]
  Q -->|old draft| RV["Re-check time-sensitive facts<br/>recheck.md"]
  RV -->|changed or gone| Q
  Q --> EX(["Export CSV"])
```

Inside the graph, two stages work across prospects: **gather** and **extract** share one
search and one extraction per company, and **account_plan** waits for colleagues at the same
company so each gets a different opener.
"""


def mermaid() -> str:
    """The compiled graph as a flowchart, with stage labels and who decides at each stage."""
    graph = build_graph(STAGES).get_graph()
    labels = {s.name: s.label for s in STAGES}
    lines = ["flowchart TD"]
    for node in graph.nodes:
        if node == "__start__":
            lines.append('  start(["start"])')
        elif node == "__end__":
            lines.append('  stop(["end"])')
        elif node == "finish":
            lines.append('  finish["finish<br/>ready for review, or low signal"]')
        else:
            info = STAGE_INFO[node]
            lines.append(f'  {node}["{labels[node]}<br/><i>{info["decided_by"]}</i>"]')
    name = {"__start__": "start", "__end__": "stop"}
    for edge in graph.edges:
        arrow = "-.->" if edge.conditional and edge.target == "__end__" else "-->"
        lines.append(f"  {name.get(edge.source, edge.source)} {arrow} {name.get(edge.target, edge.target)}")
    lines += [
        "  classDef code fill:#ccfbf1,stroke:#0f766e,color:#0b3b37",
        "  classDef model fill:#ede9fe,stroke:#6d28d9,color:#2e1065",
        "  classDef edge fill:#f1f5f9,stroke:#64748b,color:#0f172a",
    ]
    code = [n for n in graph.nodes if n in STAGE_INFO and STAGE_INFO[n]["agent"] is None]
    model = [n for n in graph.nodes if n in STAGE_INFO and STAGE_INFO[n]["agent"] is not None]
    lines += [f"  class {','.join(code)} code", f"  class {','.join(model)} model",
              "  class start,stop,finish edge"]
    return "\n".join(lines)


def table() -> str:
    rows = ["| Stage | Name in code | Decided by | Prompt file |", "|---|---|---|---|"]
    for s in STAGES:
        info = STAGE_INFO[s.name]
        agent = f"[{info['agent']}]({info['agent']})" if info["agent"] else "none (code only)"
        rows.append(f"| {s.label} | `{s.name}` | {info['decided_by']} | {agent} |")
    return "\n".join(rows)


def render() -> str:
    return (f"{HEADER}\n```mermaid\n{mermaid()}\n```\n\n"
            f"Teal: code only. Purple: a model is involved.\n\n{table()}\n{AROUND}")


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = TARGET.read_text() if TARGET.exists() else ""
        print("PIPELINE.md is up to date" if current == text else "PIPELINE.md is out of date: run scripts.draw_pipeline")
        return 0 if current == text else 1
    TARGET.write_text(text)
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
